"""Translates VHDL entities of the 63F09 design to C.

usage: gen.py <vhdl dir> <output dir> [entity ... | all]

Every entity becomes a C structure (the instance) with its create function ; every generate body and
block becomes a sub-structure with its own create function, allocated when the design is built. The
generics are fields of the instance, so the generate statements run when the design is created.
"""

import os
import re
import sys

import frontend
from cgen import Binding, E, Out, Translator, cid, mask
import tdefs
from vtypes import NCPUS_FIXED, STATIC_GENERICS, Bit, Enum, Int, Unsupported, Vec, const_int, ctype_sig, ctype_val, is_wide, leaf_count, nwords, type_of, unsupported
from pyGHDL.libghdl.vhdl import nodes, nodes_meta

K = nodes.Iir_Kind
F = nodes_meta.fields
M = nodes.Iir_Mode

BANNER = """/*
 * Generated by tools/vhdl2c from the VHDL entity %s : do not edit.
 * See docs/GENERATION.md.
 */
"""

# Entities written by hand (they wrap vendor primitives) : never translated, instantiated through
# the create functions of src/hand.
HAND_WRITTEN = ("ram_61f64x1", "ram_61f512", "ram_61f32x64", "rom_27f512",
                "bufg", "bufhce", "iobuf", "obuf", "obuft", "plle2_base", "ramb18e1", "ramb36e1")


HAND_GENERICS = {"plle2_base": ("clkfbout_mult", "clkout0_divide", "clkout1_divide", "divclk_divide")}


def ctype_decl(ct):
    return ctype_val(ct)


def zero(ct):
    if is_wide(ct):
        return "vs_w_zero()"
    if ct.kind == "int":
        return "INT64_C(%d)" % ct.left
    return "%s_zero()" % ct.cname if ct.kind in ("rec", "arr") else "0"


THREADED_ENTITIES = ("dmc_63f41",)      # the entities that get a partition (and a thread) of their own


class Iface:
    """The interface of an entity : its C name, generics and ports."""

    def __init__(self, entity, ncpus=None):
        self.entity = entity
        self.ncpus = ncpus
        self.fixed = {}
        self.name = cid(frontend.ident(entity)) + ("_n%d" % ncpus if ncpus else "")
        self.generics = []      # (cname, ct, decl)
        self.ports = []         # (cname, ct, mode, decl)
        g = nodes.Get_Generic_Chain(entity)
        while g:
            # the models of the vendor primitives take no generics, but those that set the timing of the PLL
            if self.name in HAND_WRITTEN and frontend.ident(g).lower() not in HAND_GENERICS.get(self.name, ()):
                g = nodes.Get_Chain(g)
                continue
            ct = type_of(nodes.Get_Type(g))
            self.generics.append((cid(frontend.ident(g)), ct, g))
            # the value used when a type bound depends on the generic
            try:
                if frontend.ident(g).lower() == "ncpus" and ncpus:
                    STATIC_GENERICS[g] = ncpus
                    NCPUS_FIXED[g] = ncpus
                    self.fixed[g] = ncpus
                elif frontend.ident(g).lower() in GENERIC_MAX:
                    STATIC_GENERICS[g] = GENERIC_MAX[frontend.ident(g).lower()]
                elif ct.kind == "int" and ct.hi is not None and ct.hi < 1 << 20:
                    STATIC_GENERICS[g] = ct.hi
                elif nodes.Get_Default_Value(g):
                    STATIC_GENERICS[g] = const_int(nodes.Get_Default_Value(g))
            except Unsupported:
                pass
            g = nodes.Get_Chain(g)
        for gname, cdecl in sorted(promoted_constants(entity).items()):
            ct = type_of(nodes.Get_Type(cdecl))
            self.generics.append((gname, ct, cdecl))
            if gname == "ncpus" and ncpus:
                NCPUS_FIXED[cdecl] = ncpus
                STATIC_GENERICS[cdecl] = ncpus
                self.fixed[cdecl] = ncpus
        p = nodes.Get_Port_Chain(entity)
        while p:
            self.ports.append((cid(frontend.ident(p)), type_of(nodes.Get_Type(p)), nodes.Get_Mode(p), p))
            p = nodes.Get_Chain(p)

    def params(self, struct):
        out = ["vs_kernel *k", "%s *self" % struct, "const char *path"]
        out += ["%s g_%s" % (ctype_decl(ct), n) for n, ct, d in self.generics]
        out += ["%s *%s" % (ctype_sig(ct), n) for n, ct, mode, d in self.ports]
        return ", ".join(out)


MAX_NCPUS = 8


ARCH_OF = {}        # entity -> its architecture


def promoted_constants(entity):
    """The constants of the architecture that stand for NCPUS and FPU_BY_CORE when the entity has no such generics
    (the top level fixes them) : they become parameters of the create function."""
    arch = ARCH_OF.get(entity)
    out = {}
    d = nodes.Get_Declaration_Chain(arch) if arch else 0
    while d:
        if nodes.Get_Kind(d) == K.Constant_Declaration and frontend.ident(d).lower() in ("ncpus", "fpu_by_core"):
            out[frontend.ident(d).lower()] = d
        d = nodes.Get_Chain(d)
    return out


def has_ncpus(entity):
    if "ncpus" in promoted_constants(entity):
        return True
    g = nodes.Get_Generic_Chain(entity)
    while g:
        if frontend.ident(g).lower() == "ncpus":
            return True
        g = nodes.Get_Chain(g)
    return False


# Generics that size types : the structures are built for this value (NCPUS goes from 1 to 8).
GENERIC_MAX = {"ncpus": 8}


class Design:
    def __init__(self, dfs):
        self.entities = {}
        self.archs = {}
        for df in dfs:
            for unit in frontend.units(df):
                lu = nodes.Get_Library_Unit(unit)
                k = nodes.Get_Kind(lu)
                if k == K.Entity_Declaration:
                    self.entities[frontend.ident(lu).lower()] = lu
                elif k == K.Architecture_Body:
                    ent = nodes.Get_Named_Entity(nodes.Get_Entity_Name(lu))
                    self.archs[ent] = lu          # the last architecture of an entity wins
        self.ifaces = {}
        ARCH_OF.update(self.archs)

    def iface(self, entity, ncpus=None):
        """The interface of an entity. An entity with an NCPUS generic is generated once per number of cores : the
        sizes of its signals depend on it."""
        if not has_ncpus(entity):
            ncpus = None
        elif not ncpus:
            raise Unsupported("entity %s depends on NCPUS : it is generated for 1 to %d cores" % (frontend.ident(entity), MAX_NCPUS))
        if (entity, ncpus) not in self.ifaces:
            self.ifaces[(entity, ncpus)] = Iface(entity, ncpus)
        return self.ifaces[(entity, ncpus)]


class Scope:
    """A C structure of the design : an entity instance, or the body of a generate or of a block."""

    def __init__(self, struct, up=None):
        self.struct = struct
        self.up = up
        self.depth = up.depth + 1 if up else 0
        self.fields = []        # C declarations of the members
        self.procs = []         # (function name, text, [sensitivity C expressions])
        self.init = Out()       # body of the create function
        self.bodies = []        # nested scopes
        self.includes = []
        self.nproc = 0
        self.nbody = 0
        self.nimp = 0


class EntityGen(Translator):
    def __init__(self, design, entity, ncpus=None):
        super().__init__()
        self.design = design
        self.entity = entity
        self.ncpus = ncpus
        self.arch = design.archs.get(entity)
        self.iface = design.iface(entity, ncpus)
        for decl, v in self.iface.fixed.items():
            NCPUS_FIXED[decl] = v
            STATIC_GENERICS[decl] = v
        self.name = self.iface.name
        self.root = Scope(self.name)
        self.scope = self.root

    # ------------------------------------------------------------------ declarations

    def declare_interface(self):
        s = self.scope
        for n, ct, d in self.iface.generics:
            s.fields.append("%s g_%s;" % (ctype_decl(ct), n))
            self.bindings[d] = Binding("var", "{S}->g_" + n, ct, s)
        for n, ct, mode, d in self.iface.ports:
            s.fields.append("%s *p_%s;" % (ctype_sig(ct), n))
            self.bindings[d] = Binding("sigptr", "{S}->p_" + n, ct, s)

    def declare(self, chain):
        s = self.scope
        d = chain
        while d:
            k = nodes.Get_Kind(d)
            if k == K.Signal_Declaration:
                ct = type_of(nodes.Get_Type(d))
                name = cid(frontend.ident(d))
                s.fields.append("%s s_%s;" % (ctype_sig(ct), name))
                init = nodes.Get_Default_Value(d)
                val = self.expr(init).code if init else zero(ct)
                s.init.line(tdefs.register_stmt("self->s_" + name, ct, val))
                if ct.kind not in ("rec", "arr") and not is_wide(ct):
                    s.init.line('vs_name(k, &self->s_%s, path, "%s", %d);' % (name, name, ct.width if ct.width else 64))
                self.bindings[d] = Binding("sig", "{S}->s_" + name, ct, s)
            elif k == K.Constant_Declaration and any(x[2] == d for x in self.iface.generics):
                pass            # a parameter of the create function (see promoted_constants), bound with the generics
            elif k == K.Constant_Declaration:
                ct = type_of(nodes.Get_Type(d))
                e = self.expr(nodes.Get_Default_Value(d))
                self.bindings[d] = Binding("const", "(" + e.code + ")", ct, None)
            elif k in (K.Type_Declaration, K.Subtype_Declaration, K.Anonymous_Type_Declaration,
                       K.Attribute_Declaration, K.Attribute_Specification, K.Use_Clause, K.Component_Declaration):
                pass
            elif k in (K.Function_Declaration, K.Procedure_Declaration, K.Function_Body, K.Procedure_Body):
                pass            # implicit operators, and the subprograms : translated when called
            else:
                raise unsupported(d, "declaration")
            d = nodes.Get_Chain(d)

    # ------------------------------------------------------------------ concurrent statements

    def elaborate(self, chain):
        st = chain
        while st:
            k = nodes.Get_Kind(st)
            if k == K.Sensitized_Process_Statement:
                self.process(st)
            elif k == K.Component_Instantiation_Statement:
                self.instance(st)
            elif k == K.For_Generate_Statement:
                self.for_generate(st)
            elif k == K.If_Generate_Statement:
                self.if_generate(st)
            elif k == K.Block_Statement:
                self.block(st)
            elif k == K.Concurrent_Assertion_Statement:
                pass
            else:
                raise unsupported(st, "concurrent statement")
            st = nodes.Get_Chain(st)

    def process(self, p):
        s = self.scope
        index = s.nproc
        s.nproc += 1
        fname = "%s_p%d" % (s.struct, index)
        self.scope_of[p] = s
        saved = self.out
        self.out = Out()
        o = self.out
        o.open("static void %s(void *inst)" % fname)
        o.line("%s *self = inst;" % s.struct)
        d = nodes.Get_Declaration_Chain(p)
        while d:
            k = nodes.Get_Kind(d)
            if k == K.Variable_Declaration:
                ct = type_of(nodes.Get_Type(d))
                field = "v%d_%s" % (index, cid(frontend.ident(d)))
                s.fields.append("%s %s;" % (ctype_decl(ct), field))
                init = nodes.Get_Default_Value(d)
                s.init.line("self->%s = %s;" % (field, self.expr(init).code if init else zero(ct)))
                self.bindings[d] = Binding("var", "{S}->" + field, ct, s)
            elif k == K.Constant_Declaration:
                ct = type_of(nodes.Get_Type(d))
                self.bindings[d] = Binding("const", "(" + self.expr(nodes.Get_Default_Value(d)).code + ")", ct, None)
            elif k in (K.Type_Declaration, K.Subtype_Declaration, K.Anonymous_Type_Declaration, K.Attribute_Declaration,
                       K.Attribute_Specification, K.Use_Clause):
                pass
            elif k in (K.Function_Declaration, K.Procedure_Declaration, K.Function_Body, K.Procedure_Body):
                pass
            else:
                raise unsupported(d, "process declaration")
            d = nodes.Get_Chain(d)
        self.stmts(nodes.Get_Sequential_Statement_Chain(p))
        o.close()
        sens = []
        if os.environ.get("VHDL2C_TRACE"):
            sys.stderr.write("process %s line %s\n" % (index, __import__("vtypes").where(p)))
            sys.stderr.flush()
        items = self.sensitivity_items(p)
        for item in items:
            ptr, ct, mask = self.sens_ptr(item)
            if all((ptr, mask) != (x[0], x[2]) for x in sens):
                sens.append((ptr, ct, mask))
        s.procs.append((fname, o.text(), sens))
        self.out = saved

    ASSIGNMENTS = (K.Simple_Signal_Assignment_Statement, K.Variable_Assignment_Statement,
                   K.Conditional_Signal_Assignment_Statement, K.Selected_Waveform_Assignment_Statement)

    def sensitivity_items(self, p):
        """The names of the sensitivity list of a process. For "process(all)" the list is not stored : it is the signals the
        process reads, in its statements and in the subprograms it calls (a superset is harmless : a combinational process
        woken for nothing computes what it already drove)."""
        lst = nodes.Get_Sensitivity_List(p)
        if lst > 1:
            return list(frontend.list_elements(lst))
        names = []
        seen = set()

        def signal_name(n):
            decl = nodes.Get_Named_Entity(n)
            b = self.bindings.get(decl)
            return b is not None and b.kind in ("sig", "sigptr") and b.scope is not None

        def visit(n, target=False):
            k = nodes.Get_Kind(n)
            if k in (K.Simple_Name, K.Selected_Name):
                decl = nodes.Get_Named_Entity(n)
                if not target and decl and signal_name(n):
                    names.append(n)
                return
            if k in (K.Function_Call, K.Procedure_Call):
                impl = nodes.Get_Implementation(n)
                body = nodes.Get_Subprogram_Body(impl) if impl and nodes.Get_Implicit_Definition(impl) == nodes.Iir_Predefined.PNone else 0
                if body and body not in seen:
                    seen.add(body)
                    for _, c in frontend.children(body):
                        visit(c)
            if k in (K.Indexed_Name, K.Slice_Name, K.Selected_Element) and not target:
                # a signal element or part : the longest static prefix is the object itself
                base = n
                while nodes.Get_Kind(base) in (K.Indexed_Name, K.Slice_Name, K.Selected_Element):
                    base = nodes.Get_Prefix(base)
                if nodes.Get_Kind(base) in (K.Simple_Name, K.Selected_Name) and nodes.Get_Named_Entity(base) and signal_name(base):
                    names.append(base)
                    for field, c in frontend.children(n):
                        if nodes_meta.fields(field).name in ("Index_List", "Suffix", "Prefix") and c != base:
                            visit(c)
                    return
            for field, c in frontend.children(n):
                fname = nodes_meta.fields(field).name
                if k in self.ASSIGNMENTS and fname == "Target":
                    visit(c, target=True)
                else:
                    visit(c, target)

        for _, c in frontend.children(p):
            visit(c)
        return names

    def sens_ptr(self, n):
        """(pointer, CT of the storage) of the signal a sensitivity list item stands for : an item whose index is
        not constant is sensitive to the whole object it indexes (a superset of what VHDL says)."""
        while True:
            try:
                ptr, shift, width, ct = self.sigptr(n)
                mask = None
                if isinstance(shift, int) and width is not None and not is_wide(ct) and ct.kind in ("bit", "vec") \
                        and nodes.Get_Kind(n) in (K.Indexed_Name, K.Slice_Name):
                    mask = "UINT64_C(0x%X)" % (((1 << width) - 1) << shift) if width < 64 else None
                return ptr, self.storage_ct(n, ct), mask
            except Unsupported:
                if nodes.Get_Kind(n) in (K.Indexed_Name, K.Slice_Name, K.Selected_Element):
                    n = nodes.Get_Prefix(n)
                    continue
                raise

    def storage_ct(self, n, ct):
        """CT of the storage that sigptr(n) points to (a vector part points to its vs_sig)."""
        return ct if (ct.kind in ("rec", "arr") or is_wide(ct)) else Bit()

    # ------------------------------------------------------------------ instances

    def child_entity(self, inst):
        unit = nodes.Get_Instantiated_Unit(inst)
        k = nodes.Get_Kind(unit)
        if k in (K.Simple_Name, K.Selected_Name):
            decl = nodes.Get_Named_Entity(unit)
        else:
            decl = nodes.Get_Entity_Name(unit)
            decl = nodes.Get_Named_Entity(decl)
        if nodes.Get_Kind(decl) == K.Component_Declaration:
            name = frontend.ident(decl).lower()
            if name not in self.design.entities:
                raise unsupported(inst, "no entity for the component %s" % name)
            return self.design.entities[name]
        return decl

    def unfolded(self, expr):
        """The expression as written : the analyser replaces a static expression (NCPUS) by its value, and keeps what
        was written as the origin of the literal."""
        k = nodes.Get_Kind(expr)
        if k in (K.Integer_Literal, K.Enumeration_Literal, K.Physical_Int_Literal, K.Floating_Point_Literal):
            if frontend.has_field(k, frontend.nodes_meta.fields.Literal_Origin):
                origin = nodes.Get_Literal_Origin(expr)
                if origin:
                    return origin
        return expr

    def instance(self, inst):
        s = self.scope
        entity = self.child_entity(inst)
        label = cid(frontend.ident(inst))
        iface = self.design.iface(entity, self.ncpus)
        cname = iface.name
        field = "c_%s_%d" % (label, s.nimp)
        s.nimp += 1
        if cname in HAND_WRITTEN:
            ctype = "%s_t" % cname
            s.includes.append('#include "hand/%s.h"' % cname)
        else:
            ctype = cname
            s.includes.append('#include "%s.h"' % cname)
        s.fields.append("%s %s;" % (ctype, field))
        # generics
        gm = {}
        a = nodes.Get_Generic_Map_Aspect_Chain(inst)
        while a:
            f = nodes.Get_Formal(a)
            if f and nodes.Get_Kind(a) != K.Association_Element_Open:
                gm[frontend.ident(nodes.Get_Named_Entity(f) if nodes.Get_Kind(f) == K.Simple_Name else f).lower()] = nodes.Get_Actual(a)
            a = nodes.Get_Chain(a)
        gargs = []
        for n, ct, d in iface.generics:
            actual = gm.get(n)
            if actual is None:
                dv = nodes.Get_Default_Value(d)
                if not dv:
                    raise unsupported(inst, "generic %s has no actual and no default" % n)
                actual = dv
            gargs.append(self.expr(self.unfolded(actual)).code)
        # ports
        pm = {}
        a = nodes.Get_Port_Map_Aspect_Chain(inst)
        pos = 0
        while a:
            f = nodes.Get_Formal(a)
            if f:
                name = frontend.ident(nodes.Get_Named_Entity(f) if nodes.Get_Kind(f) == K.Simple_Name else f).lower() \
                    if nodes.Get_Kind(f) in (K.Simple_Name, K.Selected_Name) else None
                if name is None:
                    raise unsupported(a, "partial association of a port")
            else:
                name = iface.ports[pos][0]
            pm[name] = a
            pos += 1
            a = nodes.Get_Chain(a)
        pargs = []
        for n, ct, mode, d in iface.ports:
            pargs.append(self.port_actual(inst, n, ct, mode, pm.get(n)))
        if frontend.ident(entity).lower() in THREADED_ENTITIES:
            self.threaded_instance(cname, field, label, iface, gargs, pargs)
            return
        s.init.line("%s_create(%s);" % (cname, ", ".join(
            ["k", "&self->" + field, 'vs_join(k, path, "%s")' % label] + gargs + pargs)))

    def threaded_instance(self, cname, field, label, iface, gargs, pargs):
        """An instance that has a partition of its own when the kernel is threaded (k->threaded) : each of its ports is a signal
        of that partition, tied to the signal of the parent that the port is connected to ; the ties are crossed by the
        mail of the kernel, so the two partitions are two threads. Otherwise the ports are the signals of the parent."""
        s = self.scope
        names = [g[0] for g in iface.generics]
        cpu = gargs[names.index("cpu_number")]
        s.init.line("{")
        decls = []
        for i, (n, ct, mode, d) in enumerate(iface.ports):
            decls.append("%s *p%d = %s;" % (ctype_sig(ct), i, pargs[i]))
        for l in decls:
            s.init.line(l)
        s.init.line("if (k->threaded)")
        s.init.line("{")
        s.init.line("vs_part_enter(k, 1 + (unsigned) (%s));" % cpu)
        for i, (n, ct, mode, d) in enumerate(iface.ports):
            own = self.private_signal(ct, "w_%s" % n, "0")           # registered in the partition of the instance
            nleaf = leaf_count(ct)
            s.init.line("{")
            s.init.line("vs_sig *ma[%d], *wa[%d];" % (nleaf, nleaf))
            s.init.line("{ vs_sig **out = ma; size_t n = 0; %s }" % tdefs.leaves_stmt("(*p%d)" % i, ct))
            s.init.line("{ vs_sig **out = wa; size_t n = 0; %s }" % tdefs.leaves_stmt(own[1:], ct))
            if mode in (M.Out_Mode, M.Buffer_Mode, M.Linkage_Mode):
                s.init.line("vs_tie_all(wa, ma, %d);" % nleaf)
            elif mode == M.Inout_Mode:
                s.init.line("vs_tie_all(ma, wa, %d);" % nleaf)
                s.init.line("vs_tie_all(wa, ma, %d);" % nleaf)
            else:
                s.init.line("vs_tie_all(ma, wa, %d);" % nleaf)
            s.init.line("p%d = %s;" % (i, own))
            s.init.line("}")
        s.init.line("}")
        s.init.line("%s_create(%s);" % (cname, ", ".join(
            ["k", "&self->" + field, 'vs_join(k, path, "%s")' % label] + gargs + ["p%d" % i for i in range(len(pargs))])))
        s.init.line("if (k->threaded)")
        s.init.line("{")
        s.init.line("vs_part_enter(k, 0);")
        s.init.line("}")
        s.init.line("}")

    def port_actual(self, inst, name, ct, mode, assoc):
        """C expression of the vs_sig a port is connected to."""
        s = self.scope
        out_like = mode in (M.Out_Mode, M.Inout_Mode, M.Buffer_Mode, M.Linkage_Mode)
        if assoc is None or nodes.Get_Kind(assoc) == K.Association_Element_Open:
            sig = self.private_signal(ct, "open_%s" % name, "0")
            return sig
        actual = nodes.Get_Actual(assoc)
        k = nodes.Get_Kind(actual)
        if k in (K.Simple_Name, K.Selected_Name):
            decl = nodes.Get_Named_Entity(actual)
            b = self.bindings.get(decl)
            if b is not None and b.kind in ("sig", "sigptr"):
                return self.bc(b) if b.kind == "sigptr" else "&" + self.bc(b)
        if k in (K.Selected_Element, K.Indexed_Name):
            # a field of a record, an element of an array : an object of its own, which the port aliases
            try:
                pk, pcode, pct = self.path(actual)
            except Unsupported:
                pk = None
            if pk == "sig" and pct.kind == ct.kind and pct.width == ct.width and (pct.kind != "vec" or True):
                return "&" + pcode
        if k in (K.Indexed_Name, K.Slice_Name):
            code, bct, lo, width = self.sigpart(actual)
            if bct.kind == "vec":
                own = self.private_signal(ct, "tie_%s" % name, "0")
                self.tie_vector(own, ct, code, bct, lo, width, out_like, mode == M.Inout_Mode)
                return own
            kind, pcode, pct = self.path(actual)
            if kind == "sig" and pct.kind in ("rec", "arr"):
                return "&" + pcode
            raise unsupported(actual, "port connected to this part of a signal")
        if out_like:
            raise unsupported(actual, "output port connected to an expression")
        # an expression : an implicit signal driven by it
        e = self.expr_as(actual, ct)
        own = self.private_signal(ct, "imp_%s" % name, e.code if self.is_constant(actual) else "0")
        if not self.is_constant(actual):
            self.implicit_process(own, e, actual)
        return own

    def tie_vector(self, own, ct, code, bct, lo, width, out_like, both=False):
        """Links the bits [lo, lo + width) of the vector signal `code` to the port signal `own` : zero-delay ties,
        one per piece that stays inside one 64-bit word on both sides."""
        s = self.scope

        def word(base, base_ct, bit):
            if is_wide(base_ct):
                return "&%s.w[%d]" % (base, bit // 64)
            return "&%s" % base

        if isinstance(lo, str):
            # one bit at a position computed when the design is built
            assert width == 1
            src = ("&%s.w[(%s) / 64]" % (code, lo)) if is_wide(bct) else "&%s" % code
            dst = word(own[1:], ct, 0)
            if out_like:
                s.init.line("vs_tie_fields(%s, 0, %s, (%s) %% 64, 1);" % (dst, src, lo))
            if both or not out_like:
                s.init.line("vs_tie_fields(%s, (%s) %% 64, %s, 0, 1);" % (src, lo, dst))
            return
        i = 0
        while i < width:
            src_bit, dst_bit = lo + i, i
            n = min(64 - src_bit % 64, 64 - dst_bit % 64, width - i)
            src = word(code, bct, src_bit)
            dst = word(own[1:], ct, dst_bit)
            if out_like:
                s.init.line("vs_tie_fields(%s, %d, %s, %d, %d);" % (dst, dst_bit % 64, src, src_bit % 64, n))
            if both or not out_like:
                s.init.line("vs_tie_fields(%s, %d, %s, %d, %d);" % (src, src_bit % 64, dst, dst_bit % 64, n))
            i += n

    def is_constant(self, expr):
        for n in frontend.walk(expr):
            if nodes.Get_Kind(n) in (K.Simple_Name, K.Selected_Name):
                decl = nodes.Get_Named_Entity(n)
                b = self.bindings.get(decl)
                if b is not None and b.kind in ("sig", "sigptr"):
                    return False
        return True

    def private_signal(self, ct, hint, init):
        """A signal of the current scope that belongs to no VHDL declaration."""
        s = self.scope
        field = "x%d_%s" % (s.nimp, hint)
        s.nimp += 1
        s.fields.append("%s %s;" % (ctype_sig(ct), field))
        if init == "0" and ct.kind in ("rec", "arr"):
            init = "%s_zero()" % ct.cname
        elif init == "0" and is_wide(ct):
            init = "vs_w_zero()"
        s.init.line(tdefs.register_stmt("self->" + field, ct, init))
        if ct.kind not in ("rec", "arr") and not is_wide(ct):
            s.init.line('vs_name(k, &self->%s, path, "%s", %d);' % (field, hint, ct.width or 64))
        return "&self->" + field

    def implicit_process(self, sigexpr, e, expr):
        s = self.scope
        fname = "%s_i%d" % (s.struct, s.nproc)
        s.nproc += 1
        body = Out()
        body.open("static void %s(void *inst)" % fname)
        body.line("%s *self = inst;" % s.struct)
        body.line("vs_drive(%s, (uint64_t)(%s));" % (sigexpr, e.code))
        body.close()
        sens = []
        for n in frontend.walk(expr):
            if nodes.Get_Kind(n) in (K.Simple_Name, K.Selected_Name):
                b = self.bindings.get(nodes.Get_Named_Entity(n))
                if b is not None and b.kind in ("sig", "sigptr"):
                    p = self.bc(b) if b.kind == "sigptr" else "&" + self.bc(b)
                    if all(p != x[0] for x in sens):
                        sens.append((p, b.ct if (b.ct.kind in ("rec", "arr") or is_wide(b.ct)) else Bit(), None))
        s.procs.append((fname, body.text(), sens))

    # ------------------------------------------------------------------ generate and block

    def new_body(self, label):
        parent = self.scope
        name = "%s_g%d" % (self.name, self.nbodies)
        self.nbodies += 1
        sc = Scope(name, parent)
        sc.fields.append("struct %s *up;" % parent.struct)
        return sc

    def build_body(self, sc, body_node, param=None):
        """Translates a generate body into scope `sc` ; returns after restoring the current scope."""
        saved_scope, saved_out = self.scope, self.out
        self.scope = sc
        self.scope_of[body_node] = sc
        if param is not None:
            sc.fields.append("int64_t gp_%s;" % cid(frontend.ident(param)))
            self.bindings[param] = Binding("var", "{S}->gp_" + cid(frontend.ident(param)), Int(), sc)
        self.declare(nodes.Get_Declaration_Chain(body_node))
        self.elaborate(nodes.Get_Concurrent_Statement_Chain(body_node))
        self.scope, self.out = saved_scope, saved_out
        saved_scope.bodies.append(sc)

    def body_label(self, node):
        return cid(frontend.ident(node)) if nodes.Get_Label(node) else "g"

    def for_generate(self, g):
        parent = self.scope
        spec = nodes.Get_Parameter_Specification(g)
        left, right, asc = self.loop_range(spec)
        sc = self.new_body(None)
        label = cid(frontend.ident(g))
        self.build_body(sc, nodes.Get_Generate_Statement_Body(g), spec)
        field = "g_%s_%d" % (label, parent.nimp)
        parent.nimp += 1
        parent.fields.append("struct %s *%s;" % (sc.struct, field))
        parent.fields.append("int64_t n_%s;" % field)
        o = parent.init
        o.open("")
        o.line("int64_t l = %s, r = %s, i, n;" % (left, right))
        o.line("n = %s;" % ("r >= l ? r - l + 1 : 0" if asc else "l >= r ? l - r + 1 : 0"))
        o.line("self->n_%s = n;" % field)
        o.line("self->%s = vs_alloc(k, (size_t) (n > 0 ? n : 1) * sizeof(*self->%s));" % (field, field))
        o.open("for (i = 0; i < n; i++)")
        o.line("char name[64];")
        o.line("struct %s *b = &self->%s[i];" % (sc.struct, field))
        o.line("int64_t v = %s;" % ("l + i" if asc else "l - i"))
        o.line("snprintf(name, sizeof(name), \"%s(%%lld)\", (long long) v);" % label)
        o.line("b->up = self;")
        o.line("b->gp_%s = v;" % cid(frontend.ident(spec)))
        o.line("%s_create(k, b, vs_join(k, path, name));" % sc.struct)
        o.close()
        o.close()

    def if_generate(self, g):
        parent = self.scope
        label = cid(frontend.ident(g))
        o = parent.init
        clause = g
        first = True
        while clause:
            cond = nodes.Get_Condition(clause)
            static = None
            if cond:
                try:
                    static = bool(const_int(cond))
                except Unsupported:
                    pass
            if static is False:
                clause = nodes.Get_Generate_Else_Clause(clause)      # this branch does not exist in this variant
                continue
            if static:
                cond = None
                first = True
            sc = self.new_body(None)
            self.build_body(sc, nodes.Get_Generate_Statement_Body(clause))
            field = "g_%s_%d" % (label, parent.nimp)
            parent.nimp += 1
            parent.fields.append("struct %s *%s;" % (sc.struct, field))
            if cond:
                o.open("%sif (%s)" % ("" if first else "else ", self.expr(cond).code))
            elif static or first:
                o.open("")          # the branches before it do not exist in this variant
            else:
                o.open("else")
            o.line("self->%s = vs_alloc(k, sizeof(*self->%s));" % (field, field))
            o.line("self->%s->up = self;" % field)
            o.line('%s_create(k, self->%s, vs_join(k, path, "%s"));' % (sc.struct, field, label))
            o.close()
            first = False
            if static:
                break
            clause = nodes.Get_Generate_Else_Clause(clause)

    def block(self, b):
        parent = self.scope
        label = cid(frontend.ident(b))
        sc = self.new_body(None)
        # a block has declarations and statements like a generate body
        saved_scope = self.scope
        self.scope = sc
        self.scope_of[b] = sc
        self.declare(nodes.Get_Declaration_Chain(b))
        self.elaborate(nodes.Get_Concurrent_Statement_Chain(b))
        self.scope = saved_scope
        parent.bodies.append(sc)
        field = "g_%s_%d" % (label, parent.nimp)
        parent.nimp += 1
        parent.fields.append("struct %s *%s;" % (sc.struct, field))
        o = parent.init
        o.line("self->%s = vs_alloc(k, sizeof(*self->%s));" % (field, field))
        o.line("self->%s->up = self;" % field)
        o.line('%s_create(k, self->%s, vs_join(k, path, "%s"));' % (sc.struct, field, label))

    # ------------------------------------------------------------------ output

    def generate(self):
        self.nbodies = 0
        self.declare_interface()
        self.scope_of[self.entity] = self.root
        if self.arch is not None:
            self.scope_of[self.arch] = self.root
            self.declare(nodes.Get_Declaration_Chain(self.arch))
            self.elaborate(nodes.Get_Concurrent_Statement_Chain(self.arch))
        return self.header(), self.source()

    def all_includes(self, scope):
        inc = list(scope.includes)
        for b in scope.bodies:
            inc += self.all_includes(b)
        return inc

    def header(self):
        guard = "GEN_%s_H" % self.name.upper()
        o = Out()
        o.line(BANNER % frontend.ident(self.entity))
        o.line("#ifndef %s" % guard)
        o.line("#define %s" % guard)
        o.line()
        o.line('#include "vsim.h"')
        o.line('#include "gen_types.h"')
        for inc in sorted(set(self.root.includes)):
            o.line(inc)
        o.line()
        for b in self.root.bodies:
            o.line("struct %s;" % b.struct)
        o.open("typedef struct %s" % self.name)
        for f in self.root.fields:
            o.line(f)
        o.close(" %s;" % self.name)
        o.line()
        o.line("void %s_create(%s);" % (self.name, self.iface.params(self.name)))
        o.line()
        o.line("#endif")
        return o.text()

    def emit_structs(self, o, sc, root):
        """The structures of all the scopes come first : the processes of a body reach their parent's fields."""
        for b in sc.bodies:
            self.emit_structs(o, b, False)
        if not root:
            o.line("struct %s" % sc.struct)
            o.line("{")
            o.level += 1
            for f in sc.fields:
                o.line(f)
            o.level -= 1
            o.line("};")
            o.line("typedef struct %s %s;" % (sc.struct, sc.struct))
            o.line()

    def emit_scope(self, o, sc, root):
        for b in sc.bodies:
            self.emit_scope(o, b, False)
        mine = [i for i in self.local_funcs.values() if i.scope is sc]
        for i in mine:
            o.lines.extend(i.text.rstrip("\n").split("\n"))
            o.line()
        for fname, body, sens in sc.procs:
            o.lines.extend(body.rstrip("\n").split("\n"))
            o.line()
        if root:
            o.open("void %s_create(%s)" % (sc.struct, self.iface.params(sc.struct)))
            o.line("(void) path;")
            for n, ct, d in self.iface.generics:
                o.line("self->g_%s = g_%s;" % (n, n))
            for n, ct, mode, d in self.iface.ports:
                o.line("self->p_%s = %s;" % (n, n))
        else:
            o.open("static void %s_create(vs_kernel *k, %s *self, const char *path)" % (sc.struct, sc.struct))
        o.lines.extend("    " + l if l else l for l in sc.init.lines)
        for fname, body, sens in sc.procs:
            if sens:
                total = sum(leaf_count(ct) for ptr, ct, mask in sens)
                masked = any(mask for ptr, ct, mask in sens)
                sens_ptrs = {ptr for ptr, ct, mask in sens}
                edges = [edge_of(body, ptr, ct, mask, sens_ptrs) for ptr, ct, mask in sens]
                edged = any(edges)
                o.open("")
                o.line("vs_sig *sens[%d];" % total)
                if masked:
                    o.line("uint64_t masks[%d];" % total)
                    o.line("{ size_t j; for (j = 0; j < %d; j++) { masks[j] = UINT64_MAX; } }" % total)
                if edged:
                    o.line("uint8_t edges[%d];" % total)
                    o.line("memset(edges, 0, sizeof(edges));")
                o.line("size_t n = 0;")
                for (ptr, ct, mask), edge in zip(sens, edges):
                    if is_wide(ct):
                        o.line("{ size_t j; for (j = 0; j < %d; j++) { sens[n++] = &(%s)->w[j]; } }" % (nwords(ct), ptr))
                    elif ct.kind in ("rec", "arr"):
                        o.line("n += %s_leaves(%s, sens + n);" % (ct.cname, ptr))
                    else:
                        if mask:
                            o.line("masks[n] = %s;" % mask)
                        if edge:
                            o.line("edges[n] = %d;" % edge)
                        o.line("sens[n++] = %s;" % ptr)
                if edged:
                    o.line("vs_register_process_edges(k, %s, self, sens, %s, edges, n);" % (fname, "masks" if masked else "NULL"))
                elif masked:
                    # (a signal that is not a single word has no mask : it is only listed with the others when it is
                    # not one of the entries above, whose masks are set one by one)
                    o.line("vs_register_process_masked(k, %s, self, sens, masks, n);" % fname)
                else:
                    o.line("vs_register_process(k, %s, self, sens, n);" % fname)
                o.close()
            else:
                o.line("vs_register_process(k, %s, self, NULL, 0);" % fname)
        o.close()
        o.line()

    def source(self):
        o = Out()
        o.line(BANNER % frontend.ident(self.entity))
        o.line('#include <stdio.h>')
        o.line('#include "%s.h"' % self.name)
        o.line('#include "gen_funcs.h"')
        for inc in sorted(set(self.all_includes(self.root)) - set(self.root.includes)):
            o.line(inc)
        o.line()
        self.emit_structs(o, self.root, True)
        for i in self.local_funcs.values():
            o.line("static %s;" % i.proto)
        o.line()
        self.emit_scope(o, self.root, True)
        return o.text()


def _balanced(text, i, open_c, close_c):
    """Index just after the group that starts at text[i] == open_c."""
    depth = 0
    while i < len(text):
        if text[i] == open_c:
            depth += 1
        elif text[i] == close_c:
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return -1


def _clocked_chain(body):
    """The conditions of the process body when it is nothing but one `if (c1) {..} else if (c2) {..} ... else if (cn) {..}`
    chain without a final else (after the `self` declaration), else None."""
    start = body.index("{")
    inner = body[start + 1:body.rindex("}")].strip()
    m = re.match(r"[A-Za-z0-9_]+ \*self = inst;\s*", inner)
    if m:
        inner = inner[m.end():]
    conds = []
    pos = 0
    while True:
        m = re.compile(r"(?:else\s+)?if\s*\(").match(inner, pos)
        if not m or (conds and not inner[pos:].startswith("else")):
            return None
        c0 = m.end() - 1
        c1 = _balanced(inner, c0, "(", ")")
        if c1 < 0:
            return None
        conds.append(inner[c0 + 1:c1 - 1].strip())
        b0 = inner.index("{", c1)
        if inner[c1:b0].strip():
            return None
        b1 = _balanced(inner, b0, "{", "}")
        if b1 < 0:
            return None
        pos = b1
        rest = inner[pos:].lstrip()
        if not rest:
            return conds
        if not re.match(r"else\s+if\s*\(", rest):
            return None             # a final else, or another statement
        pos = len(inner) - len(rest)


def edge_of(body, ptr, ct, mask, sens_ptrs):
    """1 (2) when the process only looks at the rising (falling) edges of the scalar signal `ptr` and does nothing else
    when the edge is the other one : its whole body is a chain `if (reset) {..} else if (rising_edge(ptr)) {..}` (or just
    the edge test) with no final else, and `ptr` is used nowhere else. The other edge would wake it for nothing. A process
    with statements outside such a test must be woken by every event : in VHDL a process whose sensitivity list is
    incomplete relies on the clock events to refresh its combinational part. 0 otherwise."""
    if mask or not isinstance(ct, Bit) or not ptr.startswith("&"):
        return 0
    base = re.escape(ptr[1:])
    total = len(re.findall(base + r"(?![A-Za-z0-9_])", body))
    rising = body.count("vs_rising(%s)" % ptr)
    falling = body.count("vs_falling(%s)" % ptr)
    if total == 0 or (rising and falling) or total != rising + falling:
        return 0
    conds = _clocked_chain(body)
    if not conds:
        return 0
    kind = "vs_rising" if rising else "vs_falling"
    if conds[-1] != "%s(%s)" % (kind, ptr):
        return 0
    # the other conditions (the reset) are evaluated at every wake : each signal they read must itself wake the process,
    # else the reset would only be seen at the next event of the clock, of either edge (a process(CLK) with a reset test)
    for c in conds[:-1]:
        for ref in re.findall(r"\(\*self(?:->up)*->p_[A-Za-z0-9_]+\)|self(?:->up)*->s_[A-Za-z0-9_]+(?:\.[a-z_0-9]+)?", c):
            ref = re.sub(r"\.(cur|nxt)$", "", ref)
            if "&" + ref not in sens_ptrs:
                return 0
    return 1 if rising else 2


def write_funcs(out_dir):
    """The subprograms of the packages, shared by all the entities."""
    import csub
    insts = sorted((i for i in csub.PKG_FUNCS.values() if i.text), key=lambda i: i.name)
    h = Out()
    h.line(BANNER % "(package subprograms)")
    h.line("#ifndef GEN_FUNCS_H")
    h.line("#define GEN_FUNCS_H")
    h.line()
    h.line('#include "gen_types.h"')
    h.line()
    for i in insts:
        h.line("%s;" % i.proto)
    h.line()
    h.line("#endif")
    open(os.path.join(out_dir, "gen_funcs.h"), "w").write(h.text())
    c = Out()
    c.line(BANNER % "(package subprograms)")
    c.line('#include "gen_funcs.h"')
    c.line()
    for i in insts:
        c.lines.extend(i.text.rstrip("\n").split("\n"))
        c.line()
    open(os.path.join(out_dir, "gen_funcs.c"), "w").write(c.text())


def entity_arch(design, name):
    return design.entities.get(name.lower())


def all_entities(design):
    for name in design.entities:
        if name not in HAND_WRITTEN:
            yield name


def ncpus_entity(ifaces):
    return len(ifaces) == MAX_NCPUS


def write_dispatcher(out_dir, ifaces):
    """The entity as the rest of the design sees it : one create function that chooses the variant of the core
    count (the generic NCPUS) when the design is built."""
    base = ifaces[0].name[:-len("_n1")]
    names = [i.name for i in ifaces]

    params = ifaces[0].params(base)
    for i in ifaces[1:]:
        if i.params(base) != params:
            return              # the ports depend on the number of cores : only other variants instantiate it

    h = [BANNER % base, "#ifndef GEN_%s_H" % base.upper(), "#define GEN_%s_H" % base.upper(), "", '#include "vsim.h"']
    h += ['#include "%s.h"' % n for n in names]
    h += ["", "typedef union %s" % base, "{"]
    h += ["    %s n%d;" % (n, i + 1) for i, n in enumerate(names)]
    h += ["} %s;" % base, ""]
    # the composite ports have type names that depend on the order of generation : give them stable ones
    for n, ct, m, d in ifaces[0].ports:
        if ct.kind in ("rec", "arr"):
            h += ["typedef %s %s_%s_t;" % (ctype_sig(ct), base, n),
                  "static inline void %s_%s_init(vs_kernel *k, %s_%s_t *s)" % (base, n, base, n),
                  "{", "    %s_register(k, s, %s_zero());" % (ct.cname, ct.cname), "}", ""]
    h += [ "/* returns 0, or -1 when there is no variant for that number of cores */",
          "int %s_create(%s);" % (base, params.replace("%s *self" % base, "%s *self" % base)), "", "#endif", ""]
    open(os.path.join(out_dir, base + ".h"), "w").write("\n".join(h))
    # the call passes the generics and ports on, by name
    call_args = ["k", "&self->n%d", "path"] + ["g_%s" % n for n, ct, d in ifaces[0].generics] + [n for n, ct, m, d in ifaces[0].ports]
    c = [BANNER % base, '#include "%s.h"' % base, "", "int %s_create(%s)" % (base, params), "{", "    switch (g_ncpus)", "    {"]
    for i, n in enumerate(names):
        a = list(call_args)
        a[1] = "&self->n%d" % (i + 1)
        c += ["        case %d:" % (i + 1), "            %s_create(%s);" % (n, ", ".join(a)), "            return 0;"]
    c += ["        default:", "            return -1;", "    }", "}", ""]
    open(os.path.join(out_dir, base + ".c"), "w").write("\n".join(c))
    print("%s : dispatcher over %d variants" % (base, len(names)))


def main(argv):
    vhdl_dir, out_dir = argv[1], argv[2]
    names = argv[3:]
    frontend.init()
    here = os.path.dirname(os.path.abspath(__file__))
    dfs = frontend.load_project(vhdl_dir, os.path.join(here, "sources.list"))
    design = Design(dfs)
    if names == ["all"]:
        names = list(all_entities(design))
    os.makedirs(out_dir, exist_ok=True)
    failed = 0
    for name in names:
        entity = design.entities.get(name.lower())
        if entity is None:
            sys.exit("no entity " + name)
        variants = range(1, MAX_NCPUS + 1) if has_ncpus(entity) else [None]
        done = []
        for ncpus in variants:
            label = name if ncpus is None else "%s (%d cores)" % (name, ncpus)
            try:
                gen = EntityGen(design, entity, ncpus)
                h, c = gen.generate()
            except Unsupported as e:
                if os.environ.get("VHDL2C_DEBUG"):
                    import traceback
                    traceback.print_exc()
                print("%s : UNSUPPORTED %s" % (label, e))
                failed += 1
                break
            except Exception as e:          # a bug of the generator : report where, and go on with the other entities
                import traceback
                if os.environ.get("VHDL2C_DEBUG"):
                    traceback.print_exc()
                last = traceback.extract_tb(e.__traceback__)[-1]
                print("%s : INTERNAL ERROR %s (%s:%d %s)" % (label, e, os.path.basename(last.filename), last.lineno, last.name))
                failed += 1
                break
            base = gen.iface.name
            open(os.path.join(out_dir, base + ".h"), "w").write(h)
            open(os.path.join(out_dir, base + ".c"), "w").write(c)
            done.append(gen.iface)
            print("%s : generated %s.c/.h" % (label, base))
        if ncpus_entity(done):
            write_dispatcher(out_dir, done)
    open(os.path.join(out_dir, "gen_types.h"), "w").write(tdefs.header())
    write_funcs(out_dir)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
