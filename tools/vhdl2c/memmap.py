#!/usr/bin/env python3
"""Reads the memory map from the address decoding of the VHDL SoC (the process that sets CS(MUX_...) from A) and writes
src/gen/memmap.h (the base of every block, for the C of src/soc) and docs/MEMORY_MAP.md (the same, for people).

usage: memmap.py VHDL_DIR OUT.h OUT.md

The decoding has the form
    if A(35 downto 16) = x"FFFFF" then CS(MUX_EPROM0) <= '1';
    elsif A(35 downto 16) = x"FFFFE" then case A(15 downto 12) is when x"F" => case A(11 downto 0) is
        when x"000" | x"001" => CS(MUX_PIA0) <= '1'; ...
and MMU_CS(i) under `when x"i"` for the MMUs. Anything the decoding does not name goes to the external bus. A block
is given by its first address and the number of addresses that select it."""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

TOKEN = re.compile(r'''
    (?P<hi>(?:els)?if\s+A\(35\s+downto\s+16\)\s*=\s*x"(?P<hival>[0-9A-Fa-f]+)"\s*then)
  | (?P<nib>case\s+A\(15\s+downto\s+12\)\s+is)
  | (?P<off>case\s+A\(11\s+downto\s+0\)\s+is)
  | (?P<end>end\s+case)
  | (?P<mmu>MMU_CS\(\s*(?P<mmuidx>\d+)\s*\)\s*<=\s*'1')
  | (?P<when>when\s+(?P<list>x"[0-9A-Fa-f]+"(?:\s*\|\s*x"[0-9A-Fa-f]+")*)\s*=>)
  | (?P<cs>CS\(\s*MUX_(?P<dev>\w+?)\s*\)\s*<=\s*'1')
''', re.X)

NAMES = {"EPROM0": "ROM", "INTRAM0": "INTRAM"}


def source(vhdl_dir):
    """The text of the file that has the decoding (the files of sources.list are looked up the way gen.py does)."""
    wanted = [l.split()[1] for l in open(os.path.join(HERE, "sources.list")) if l.strip() and not l.startswith("#")]
    for name in reversed(wanted):
        for f in sorted(os.listdir(vhdl_dir)):
            if f.lower().endswith((".vhd", ".vhdl")) and (f[:-4] == name or f[:-4].endswith("-" + name)):
                text = open(os.path.join(vhdl_dir, f), encoding="utf-8", errors="replace").read()
                if re.search(r'A\(35\s+downto\s+16\)\s*=\s*x"', text):
                    return re.sub(r"--[^\n]*", "", text)
    sys.exit("memmap.py : no file of %s has the address decoding" % vhdl_dir)


def parse(text):
    """{name: (base, count)} : count is the number of addresses that select the block (0 : the whole 64 KiB window)."""
    i = text.index('A(35 downto 16) = x"')
    i = text.rfind("if", 0, i)
    blocks = {}
    hi = nib = None
    stack = []
    for m in TOKEN.finditer(text, i):
        if m.group("hi"):
            hi, nib = int(m.group("hival"), 16), None
            stack = []
        elif m.group("nib"):
            stack.append("nib")
        elif m.group("off"):
            stack.append("off")
        elif m.group("end"):
            if stack:
                stack.pop()
        elif m.group("when"):
            values = [int(v, 16) for v in re.findall(r'x"([0-9A-Fa-f]+)"', m.group("list"))]
            if stack and stack[-1] == "nib":
                nib = values[0]
            elif stack and stack[-1] == "off":
                after = TOKEN.search(text, m.end())
                if after and after.group("cs") and after.start() - m.end() < 4:
                    base = (hi << 16) | (nib << 12) | min(values)
                    dev = after.group("dev")
                    blocks[dev] = (base, len(values))
        elif m.group("mmu"):
            blocks["MMU%s" % m.group("mmuidx")] = ((hi << 16) | (nib << 12), 0x1000)
        elif m.group("cs") and not stack and hi is not None and m.group("dev") in NAMES:
            blocks[NAMES.get(m.group("dev"), m.group("dev"))] = (hi << 16, 0x10000)
    return blocks


def header(blocks):
    o = ["/*", " * Generated by tools/vhdl2c/memmap.py from the address decoding of the VHDL SoC : do not edit.",
         " * The base of every block decoded by the SoC and the number of addresses that select it.", " */", "",
         "#ifndef GEN_MEMMAP_H", "#define GEN_MEMMAP_H", ""]
    for name, (base, size) in sorted(blocks.items(), key=lambda kv: -kv[1][0]):
        o.append("#define MM_%s_BASE UINT64_C(0x%09X)" % (name, base))
        o.append("#define MM_%s_SIZE UINT64_C(0x%X)" % (name, size))
    o += ["", "#endif", ""]
    return "\n".join(o)


def page(blocks):
    o = ["# Memory map", "",
         "Generated by `tools/vhdl2c/memmap.py` (`make gen`) from the address decoding of the VHDL SoC : do not edit.",
         "Physical addresses of 36 bits ; what the decoding does not name is the external bus (EXT0, 64 bits).", "",
         "| Base | Addresses | Block |", "| --- | --- | --- |"]
    for name, (base, size) in sorted(blocks.items(), key=lambda kv: -kv[1][0]):
        o.append("| `%09X` | %s | %s |" % (base, "64 KiB" if size == 0x10000 else "4 KiB" if size == 0x1000 else str(size), name))
    o.append("| anything else | | EXT0 |")
    return "\n".join(o) + "\n"


def main(argv):
    blocks = parse(source(argv[1]))
    if not blocks:
        sys.exit("memmap.py : no block found")
    open(argv[2], "w").write(header(blocks))
    open(argv[3], "w").write(page(blocks))


if __name__ == "__main__":
    main(sys.argv)
